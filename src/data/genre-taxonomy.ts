export function searchGenres(query: string): string[] {
  const q = query.toLowerCase().trim()
  if (!q) return GENRE_TAXONOMY.main
  return GENRE_TAXONOMY.main.filter((g) => g.includes(q))
}

export function searchSubgenres(mainGenre: string, query: string): string[] {
  const subs = GENRE_TAXONOMY.sub[mainGenre] || []
  const q = query.toLowerCase().trim()
  if (!q) return subs
  return subs.filter((s) => s.includes(q))
}
